const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('signal-window/app.js','utf8');
const label=source.match(/function mediaPlaybackLabel\(d,entry\)\{[^\n]+\}/)[0];
const context={selectedMediaOutput:'browser',browserIsVideo:e=>e.kind==='video',mediaTime:x=>String(x||0)};
vm.createContext(context);vm.runInContext(label,context);
assert(context.mediaPlaybackLabel({state:'loading'},{kind:'video'}).includes('Preparing'));
assert(context.mediaPlaybackLabel({state:'error'},{kind:'video'}).includes('could not load'));
assert.equal(context.mediaPlaybackLabel({state:'playing',position:12,duration:60},{kind:'video'}),'12 / 60');
context.selectedMediaOutput='node:server';
assert.equal(context.mediaPlaybackLabel({state:'loading',position:0,duration:60},{kind:'video'}),'0 / 60');
const element=()=>({events:{},addEventListener(name,callback){this.events[name]=callback}});
context.browserAudio=element();context.browserVideo=element();context.browserElement=context.browserVideo;
context.selectedMediaOutput='browser';context.browserMedia={active:false,state:'loading'};
context.renderMedia=()=>{};context.browserSnapshot=()=>({});
vm.runInContext(source.split('\n').find(line=>line.startsWith('for(const el of [browserAudio,browserVideo])')),context);
assert(!context.browserVideo.events.play);
context.browserVideo.events.playing();assert.equal(context.browserMedia.state,'playing');
context.browserVideo.events.error();assert.equal(context.browserMedia.state,'error');assert.equal(context.browserMedia.active,false);
console.log('Browser preparation labels and playback/error events passed');
