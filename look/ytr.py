MAX_AUDIO_BYTES=1024*1024*1024
POLL_SECONDS=3
BOOKMARK_SECONDS=5


class RadioError(ValueError):pass


def owner(value=None):
    path=Path.home()/'.config/look/radio.json'
    if value:book_reader.write_json(path,{'node':value})
    try:return json.loads(path.read_text()).get('node') or 'local'
    except (OSError,ValueError):return 'local'


class Client:
    def __init__(self,node,root=None):
        self.node=node
        self.root=Path(root or Path.home()/'.local/share/look/radio')/hashlib.sha256(node.encode()).hexdigest()[:16]
        self.root.mkdir(parents=True,exist_ok=True)
        self.offline=False
        self.revisions={}
        self.lock=threading.RLock()
        self.cancel=threading.Event()

    def request(self,action=None,**fields):
        url=fabric_files.BASE+'/v1/radio?'+urllib.parse.urlencode({'target':self.node})
        data=json.dumps(dict(fields,action=action)).encode() if action else None
        try:
            with urllib.request.urlopen(urllib.request.Request(url,data=data,headers={'Content-Type':'application/json'}),timeout=8) as response:
                result=json.load(response)
        except urllib.error.HTTPError as exc:
            try:message=json.load(exc).get('error','Radio request failed')
            except ValueError:message=str(exc)
            raise RadioError(message) from None
        if not result.get('ok'):raise RadioError(result.get('error','Radio request failed'))
        if action=='remove':
            with self.lock:
                pending=self.pending();pending.pop(fields['id'],None)
                book_reader.write_json(self.root/'bookmarks.json',pending)
        return result

    def snapshot(self):
        try:
            state=self.request();self.offline=False
            book_reader.write_json(self.root/'queue.json',state)
        except OSError:
            self.offline=True
            try:state=json.loads((self.root/'queue.json').read_text())
            except FileNotFoundError:raise RadioError('Queue owner unavailable; no local queue snapshot yet')
        pending=self.pending()
        for item in state['items']:
            if item['id'] in pending:
                item.update(position=pending[item['id']]['position'],done=pending[item['id']]['done'])
            item['cached']=self.audio_path(item).is_file()
        return state

    def audio_path(self,item):
        # IDs are generated by the queue owner; validate before filesystem use.
        value=str(item['id'])
        if len(value)!=32 or any(c not in '0123456789abcdef' for c in value):raise RadioError('Invalid radio item identity')
        return self.root/(value+'.m4a')

    def prepare(self,item):
        path=self.audio_path(item)
        if path.is_file():return path
        if self.offline:raise RadioError('This item is not cached here; reconnect to its queue owner')
        if item.get('stage')!='complete':raise RadioError(item.get('error') or 'Audio is still preparing; retry when ready')
        url=fabric_files.BASE+'/v1/radio/audio?'+urllib.parse.urlencode({'target':self.node,'id':item['id']})
        temporary=path.with_suffix('.part')
        try:
            with urllib.request.urlopen(url,timeout=10) as response,temporary.open('wb') as out:
                count=0
                while True:
                    if self.cancel.is_set():raise RadioError('Cache preparation cancelled')
                    chunk=response.read(1024*1024)
                    if not chunk:break
                    count+=len(chunk)
                    if count>MAX_AUDIO_BYTES:raise RadioError('Audio exceeds the 1 GiB per-item cache limit')
                    out.write(chunk)
                expected=response.headers.get('Content-Length')
                if not count or (expected and count!=int(expected)):raise RadioError('Incomplete audio transfer')
            os.replace(temporary,path)
        finally:temporary.unlink(missing_ok=True)
        return path

    def pending(self):
        try:return json.loads((self.root/'bookmarks.json').read_text())
        except FileNotFoundError:return {}

    def checkpoint(self,item,position,done=False):
        with self.lock:
            pending=self.pending();old=pending.get(item['id'],{})
            pending[item['id']]={'id':item['id'],'position':position,'done':done,
                'bookmark_revision':old.get('bookmark_revision',self.revisions.get(item['id'],item['bookmark_revision']))}
            book_reader.write_json(self.root/'bookmarks.json',pending)

    def sync(self):
        with self.lock:
            pending=self.pending();errors=[]
            for key,value in list(pending.items()):
                try:result=self.request('progress',**value)
                except RadioError as exc:
                    errors.append(str(exc));continue
                row=next(i for i in result['items'] if i['id']==key)
                self.revisions[key]=row['bookmark_revision']
                pending.pop(key)
                book_reader.write_json(self.root/'bookmarks.json',pending)
            if errors:raise RadioError('; '.join(dict.fromkeys(errors)))

    def resolve(self,number,keep):
        state=self.request()
        if not 1<=int(number)<=len(state['items']):raise RadioError('Choose an existing item number')
        item=state['items'][int(number)-1]
        with self.lock:
            pending=self.pending();value=pending.get(item['id'])
            if value and keep=='local':
                result=self.request('progress',**dict(value,bookmark_revision=item['bookmark_revision']))
                item=next(i for i in result['items'] if i['id']==item['id'])
            self.revisions[item['id']]=item['bookmark_revision']
            pending.pop(item['id'],None);book_reader.write_json(self.root/'bookmarks.json',pending)
        return item

    def clean(self):
        state=self.snapshot();count=0
        for item in state['items']:
            if item.get('done'):
                path=self.audio_path(item)
                if path.is_file():path.unlink();count+=1
        known={self.audio_path(item) for item in state['items']}
        for path in self.root.glob('*.m4a'):
            if path not in known:path.unlink();count+=1
        return count


class Player:
    """Use mpv's existing audio engine; no codec or audio device implementation."""
    def __init__(self):self.process=None;self.folder=None
    def command(self,*args):
        if not self.process or self.process.poll() is not None:return None
        with socket.socket(socket.AF_UNIX,socket.SOCK_STREAM) as client:
            client.settimeout(.3);client.connect(str(self.folder/'ipc'))
            client.sendall((json.dumps({'command':args,'request_id':1})+'\n').encode())
            stream=client.makefile('rb')
            for line in stream:
                result=json.loads(line)
                if result.get('request_id')==1:
                    if result.get('error')!='success':raise RadioError('mpv: '+str(result.get('error')))
                    return result.get('data')
        return None
    def start(self,path,position):
        if self.process and self.process.poll() is not None:
            self.close();self.process=None
        if not self.process:
            binary=book_reader.binary('mpv')
            if not binary:raise RadioError('Install mpv with LOOK setup to listen')
            self.folder=Path(tempfile.mkdtemp(prefix='lk-ytr-'))
            self.process=subprocess.Popen([binary,'--no-config','--idle=yes','--keep-open=yes','--no-video','--audio-display=no',
                '--input-ipc-server='+str(self.folder/'ipc')],stdin=subprocess.DEVNULL,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
            deadline=time.monotonic()+3
            while not (self.folder/'ipc').exists():
                if self.process.poll() is not None or time.monotonic()>deadline:raise RadioError('mpv could not start')
                time.sleep(.02)
        self.command('loadfile',str(path),'replace',-1,{'start':str(max(0,position))})
        self.command('set_property','pause',False)
    def get(self,name):
        try:return self.command('get_property',name)
        except (OSError,ValueError):return None
    def close(self):
        if self.process:
            try:self.command('quit');self.process.wait(timeout=2)
            except (OSError,subprocess.TimeoutExpired):self.process.terminate()
        if self.folder:shutil.rmtree(self.folder,ignore_errors=True)


def terminal_frame(rows, footer):
    """Paint content and footer before clearing only the unused tail."""
    return '\033[H'+'\n'.join(line+'\033[K' for line in [*rows,*footer])+'\033[J'


def desk(client,ui):
    fd=sys.stdin.fileno();prior=termios.tcgetattr(fd)
    pool=concurrent.futures.ThreadPoolExecutor(max_workers=1)
    player=Player();state={'items':[]};selected=0;current=None;message='Connecting…';future=None;task='';playing=False;waiting=False
    next_poll=0;last_bookmark=0;prefetched=set();visual=False;last_frame=None;started=time.monotonic();position=0
    def submit(kind,fn,*args):
        nonlocal future,task
        task=kind;future=pool.submit(fn,*args)
    def checkpoint(done=False):
        if current:client.checkpoint(current,position,done or current.get('done',False))
    def prompt(label):
        nonlocal last_frame
        last_frame=None
        termios.tcsetattr(fd,termios.TCSADRAIN,prior)
        try:return input('\n'+label).strip().strip('\"\'')
        finally:tty.setcbreak(fd)
    try:
        tty.setcbreak(fd);print('\033[?1049h',end='')
        while True:
            now=time.monotonic()
            if future and future.done():
                try:
                    result=future.result()
                    if task=='snapshot':state=result;message='Offline · cached audio only' if client.offline else 'Queue owner · '+str(state.get('node',client.node))
                    elif task=='play':player.start(result,current.get('position',0));playing=True;waiting=False;message='Listening · '+current.get('title',current['url'])
                    elif task=='mutation':state=result;message='Queue updated'
                    elif task=='sync':message='Listening position saved'
                    elif task=='clean':message='Removed '+str(result)+' finished local audio copies'
                except Exception as exc:
                    message=str(exc);playing=False if task=='play' else playing
                    if task=='play':waiting=current.get('stage') not in {'complete','failed','cancelled','expired'}
                future=None;next_poll=now+POLL_SECONDS
            items=state['items'];selected=max(0,min(selected,len(items)-1))
            if current and playing:
                position=float(player.get('time-pos') or position)
                if player.get('eof-reached') and not future:
                    current['done']=True;checkpoint(True);playing=False
                    following=next((i+1 for i,item in enumerate(items) if item['id']==current['id']),len(items))
                    if following<len(items) and not future:
                        current=dict(items[following]);selected=following;submit('play',client.prepare,current)
                elif now-last_bookmark>=BOOKMARK_SECONDS and not future:
                    checkpoint();submit('sync',client.sync);last_bookmark=now
            if waiting and not future and current:
                updated=next((x for x in items if x['id']==current['id']),None)
                if updated and updated.get('stage')=='complete':
                    current.update(updated);waiting=False;submit('play',client.prepare,current)
                elif updated and updated.get('stage') in {'failed','cancelled','expired'}:
                    waiting=False;message=updated.get('error') or 'Download unavailable; R retries'
            if not future and now>=next_poll:submit('snapshot',client.snapshot)
            if not future and not client.offline:
                index=next((i for i,x in enumerate(items) if current and x['id']==current['id']),selected)
                upcoming=items[index:index+2]
                candidate=next((x for x in upcoming if x.get('stage')=='complete' and not client.audio_path(x).is_file() and x['id'] not in prefetched),None)
                if candidate:
                    prefetched.add(candidate['id']);submit('prefetch',client.prepare,candidate)
            width,height=shutil.get_terminal_size((80,24));width=max(20,width-1)
            rows=['YOUTUBE RADIO · listen later',message,'']
            if current:rows+=['▶ '+current.get('title',current['url']),f'{int(position)//60}:{int(position)%60:02d} · Space pause/resume · ←/→ seek','']
            if visual:rows+=player_visuals.frame(player_visuals.NAMES.index('Tape Echo')+1,width,min(7,max(2,height//4)),now-started,playing and not bool(player.get('pause')))
            page=max(1,height-len(rows)-6);start=max(0,selected-page//2)
            for i,item in list(enumerate(items))[start:start+page]:
                cache='offline ready' if client.audio_path(item).is_file() else item.get('stage','queued')
                rows.append(('› ' if i==selected else '  ')+f'{i+1}. '+('✓ ' if item.get('done') else '')+item.get('title',item['url'])+' · '+cache)
            if not items:rows.append('A add a YouTube link · audio prepares on the queue owner')
            rendered=[]
            for index,row in enumerate(rows):
                line=ui._ansi_clip(re.sub(r'[\x00-\x1f\x7f-\x9f]',' ',row),width)
                rendered.append(ui._c(line,'1;34') if index==0 or row.startswith('› ') else line)
            footer=terminal_style.command_lines('Enter play · A add · Space pause · N next · U/D reorder · X remove · R retry · O original · C clean finished · V visual · Q save/quit',width)
            frame=terminal_frame(rendered,footer)
            if frame!=last_frame:
                sys.stdout.write(frame);sys.stdout.flush();last_frame=frame
            key=ui._read_tty_key(fd,.15)
            if key in {'q','Q','esc','\x03'}:break
            if key in {'up','down','pageup','pagedown','home','end'}:
                selected=0 if key=='home' else len(items)-1 if key=='end' else max(0,min(len(items)-1,selected+{'up':-1,'down':1,'pageup':-page,'pagedown':page}[key]));continue
            if key in {'v','V'}:visual=not visual;continue
            if key==' ':player.command('cycle','pause');continue
            if key in {'left','right'}:player.command('seek',-10 if key=='left' else 10,'relative');continue
            if not key or future:continue
            if key in {'c','C'}:submit('clean',client.clean)
            elif key in {'a','A'}:
                url=prompt('YouTube link: ')
                if url:submit('mutation',functools.partial(client.request,'add',url=url))
            elif items:
                item=items[selected]
                if key in {'enter','\r','\n','n','N'}:
                    checkpoint()
                    if key in {'n','N'} and current:
                        selected=min(len(items)-1,next((i+1 for i,x in enumerate(items) if x['id']==current['id']),selected));item=items[selected]
                    current=dict(item);position=0 if current.get('done') else current.get('position',0);current['position']=position;current['done']=False;playing=False;submit('play',client.prepare,current)
                elif key in {'u','U','d','D'}:submit('mutation',functools.partial(client.request,'move',id=item['id'],delta=-1 if key.lower()=='u' else 1))
                elif key in {'x','X'}:
                    if current and current['id']==item['id']:checkpoint();player.command('stop');current=None;playing=False
                    submit('mutation',functools.partial(client.request,'remove',id=item['id']))
                elif key in {'r','R'}:submit('mutation',functools.partial(client.request,'retry',id=item['id']))
                elif key in {'o','O'}:subprocess.Popen(['open' if sys.platform=='darwin' else 'xdg-open',item['url']],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    except KeyboardInterrupt:
        message="Radio closed; bookmark saved locally"
    finally:
        client.cancel.set();player.close();pool.shutdown(wait=True);checkpoint()
        try:client.sync()
        except Exception as exc:message='Local bookmark retained: '+str(exc)
        termios.tcsetattr(fd,termios.TCSADRAIN,prior);print('\033[?1049l'+message)
    return 0


def main(argv=None,ui=None):
    parser=argparse.ArgumentParser(prog='lk ytr',description='YouTube Radio · audio-only listen-later queue')
    parser.add_argument('action',nargs='?',default='desk',help='URL, desk, list, clean, sync, or resolve')
    parser.add_argument('number',nargs='?',type=int,help='Item number for bookmark conflict resolution')
    parser.add_argument('--keep',choices=('local','remote'),help='Explicit bookmark conflict resolution')
    parser.add_argument('--node',help='Queue owner; remembers this choice on this endpoint')
    args=parser.parse_args(argv);client=Client(owner(args.node))
    try:
        if args.action.startswith(('https://','http://')):
            state=client.request('add',url=args.action);print('Queued audio on '+state['node']+' · lk ytr to listen');return 0
        if args.action=='resolve':
            if not args.number or args.number<1 or not args.keep:raise RadioError('Use lk ytr resolve NUMBER --keep local|remote')
            client.resolve(args.number,args.keep);print('Bookmark conflict resolved');return 0
        if args.action=='clean':print('Removed',client.clean(),'finished local audio copies; owner files retained');return 0
        if args.action=='sync':client.sync();print('Bookmarks synchronized');return 0
        if args.action not in {'desk','list'}:parser.error('Use a video URL, desk, list, clean or sync')
        if args.action=='list' or not sys.stdin.isatty():
            state=client.snapshot()
            for i,item in enumerate(state['items'],1):print(i,item.get('title',item['url']),item.get('stage'),'cached' if item['cached'] else '')
            return 0
        return desk(client,ui)
    except (OSError,ValueError) as exc:print('YouTube Radio · '+str(exc));return 1
